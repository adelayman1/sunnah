// ============================================================

function renderFilters() {
    if (!filtersContainer) return;

    const favCount = getFavorites().length;

    const options = [
        {
            id: "all",
            name: "الكل"
        },

        {
            id: "favorites",
            name: `المحفوظات 🔖 (${favCount})`
        },

        ...categories
    ];

    filtersContainer.innerHTML = options
        .map(
            (option) => `
                <button
                    type="button"
                    class="filter-chip ${
                        option.id === activeCategory
                            ? "active"
                            : ""
                    }"
                    data-category="${option.id}"
                >
                    ${option.name}
                </button>
            `
        )
        .join("");

    filtersContainer
        .querySelectorAll(".filter-chip")
        .forEach((button) => {

            button.addEventListener("click", () => {

                activeCategory = button.dataset.category;

                renderFilters();
                renderCards();

            });

        });
}


// ============================================================
// Cards
// ============================================================

function renderCards() {
    if (!cardsGrid) return;

    let items = sunnahs;

    // ------------------------------------------
    // الكل
    // ------------------------------------------

    if (activeCategory === "all") {

        items = sunnahs;

    }

    // ------------------------------------------
    // المفضلة
    // ------------------------------------------

    else if (activeCategory === "favorites") {

        const favs = getFavorites();

        items = sunnahs.filter((item) =>
            favs.includes(item.id)
        );

    }

    // ------------------------------------------
    // قسم محدد
    // ------------------------------------------

    else {

        items = sunnahs.filter(
            (item) => item.category === activeCategory
        );

    }


    // ------------------------------------------
    // لا توجد عناصر
    // ------------------------------------------

    if (!items.length) {

        if (activeCategory === "favorites") {

            cardsGrid.innerHTML = `
                <div class="empty-state">
                    لم تقم بإضافة أي سنن إلى المحفوظات بعد.
                    <br>
                    اضغط على رمز الإشارة المرجعية 🔖
                    في أي سنة للحفظ هنا.
                </div>
            `;

        } else {

            cardsGrid.innerHTML = `
                <div class="empty-state">
                    لا توجد عناصر في هذا القسم حاليًا.
                </div>
            `;

        }

        return;
    }


    // ------------------------------------------
    // عرض الكروت
    // ------------------------------------------

    cardsGrid.innerHTML = items
        .map((item) => cardTemplate(item))
        .join("");
}


// ============================================================
// INIT
// ============================================================

function initPage() {

    // مهم جدًا:
    // نضمن أن الصفحة تبدأ دائمًا على "الكل"
    activeCategory = "all";

    renderCategories();

    renderFeatured();

    renderFilters();

    // مهم جدًا:
    // عرض جميع الكروت مباشرة عند فتح الصفحة
    renderCards();
}


// ============================================================
// تشغيل بعد تحميل DOM
// ============================================================

if (document.readyState === "loading") {

    document.addEventListener(
        "DOMContentLoaded",
        initPage
    );

} else {

    initPage();

}